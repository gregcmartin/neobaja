# A FIX tile carries one palette index per pixel, so a coloured HUD needs a
# second copy of the glyph table rather than a second palette.  Codes 0x20-0x7F
# are the ivory face, 0x80-0x9F the cyan HUD furniture, and 0xA0-0xFF the same
# ASCII glyphs in amber (code + 0x80).
SHADE_IVORY = 1
SHADE_AMBER = 2
SHADE_CYAN = 3
AMBER_OFFSET = 0x80

# Palette entries are written into the sheet as flat marker colours; the
# compiler maps them to the declared FIX palette by exact index.
MARKERS = {
    SHADE_IVORY: (0xF2, 0xED, 0xDF),
    SHADE_AMBER: (0xFF, 0xC1, 0x32),
    SHADE_CYAN: (0x63, 0xDC, 0xEF),
}


def _blit(sheet: np.ndarray, code: int, rows: tuple[str, ...], shade: int) -> None:
    if not 0 <= code <= 255:
        raise SystemExit(f"glyph code {code} is outside the FIX table")
    cell_x, cell_y = (code % 16) * 8, (code // 16) * 8
    colour = MARKERS[shade]
    for y, row in enumerate(rows):
        for x, pixel in enumerate(row):
            if pixel != ".":
                sheet[cell_y + y, cell_x + x] = (colour[0], colour[1], colour[2], 255)


def build_sheet() -> np.ndarray:
    """Return the 128x128 RGBA FIX source: a 16x16 grid of 8x8 cells."""
    sheet = np.zeros((128, 128, 4), dtype=np.int32)
    for character, rows in GLYPHS.items():
        code = ord(character)
        _blit(sheet, code, rows, SHADE_IVORY)
        _blit(sheet, code + AMBER_OFFSET, rows, SHADE_AMBER)
    for character, rows in BLOCKS.items():
        _blit(sheet, ord(character), rows, SHADE_CYAN)
    return sheet


def coverage() -> str:
    table = dict(GLYPHS)
    table.update(BLOCKS)
    return "".join(sorted(k for k in table if ord(k) < 128))
