SHADE_AMBER = 2
SHADE_CYAN = 3
SHADE_SHADOW = 6
SHADE_LIME = 11
SHADE_LCD = 10
AMBER_OFFSET = 0x80
# A third small set in LCD green on the LCD's dark ground, at GREEN_BASE +
# the ASCII code, for the speed readout and lap times.
